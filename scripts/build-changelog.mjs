#!/usr/bin/env node
/**
 * Generate the data room's change log from this repository's git history.
 *
 * Spec: docs/data-room.md ("The change log is the git history").
 *
 * The runtime image has no .git (the Dockerfile copies functions/src, not the
 * repository), so the log has to be generated here and committed as a module
 * that tsc emits. `npm run predeploy` runs this, which means a deploy publishes
 * the history the deploy actually contains.
 *
 * Every commit subject in this repository is published the moment it deploys.
 * A commit whose message contains [private] is still counted in the daily pace
 * and never quoted, which is the escape hatch for a change that cannot be
 * named. Use it rather than writing a vague subject: the log is worth reading
 * only because it is the real one.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(REPO, 'functions', 'src', 'content', 'changelog.ts');

/** How many named changes the page carries. The daily pace covers everything;
 *  the quoted list is what a person actually reads before scrolling past. */
const QUOTED = 150;

// Field and record separators that cannot occur in a commit message.
const FS = '\x1f';
const RS = '\x1e';

function git(args) {
  return execFileSync('git', args, { cwd: REPO, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
}

const raw = git(['log', '--no-merges', `--pretty=format:%h${FS}%aI${FS}%s${FS}%b${RS}`]);

const commits = [];
for (const chunk of raw.split(RS)) {
  const record = chunk.trim();
  if (!record) continue;
  const [hash, iso, subject, body = ''] = record.split(FS);
  if (!hash || !iso || !subject) continue;
  const isPrivate = /\[private\]/i.test(`${subject} ${body}`);
  commits.push({ date: iso.slice(0, 10), subject: isPrivate ? null : subject.trim() });
}
commits.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

const byDay = new Map();
for (const c of commits) byDay.set(c.date, (byDay.get(c.date) || 0) + 1);
const daily = [...byDay.entries()]
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([date, changes]) => ({ date, changes }));

const quoted = commits.filter(c => c.subject).slice(0, QUOTED);

const esc = s => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const out = `/**
 * GENERATED by scripts/build-changelog.mjs from this repository's git history.
 * Do not edit by hand: run \`node scripts/build-changelog.mjs\` (npm run
 * predeploy does it for you). Spec: docs/data-room.md.
 */

export interface ChangeDay { date: string; changes: number }
export interface Change { date: string; subject: string }

/** Changes shipped per day over the whole history, private ones counted but
 *  not named. This is the pace, and it is not editable prose. */
export const CHANGE_DAYS: ChangeDay[] = [
${daily.map(d => `  { date: '${d.date}', changes: ${d.changes} },`).join('\n')}
];

/** The newest ${QUOTED} named changes, newest first. */
export const CHANGES: Change[] = [
${quoted.map(c => `  { date: '${c.date}', subject: '${esc(c.subject)}' },`).join('\n')}
];

/** Total commits behind CHANGE_DAYS, private included. */
export const TOTAL_CHANGES = ${commits.length};

/** The day this file was generated, which is the deploy that published it. */
export const CHANGELOG_BUILT_AT = '${new Date().toISOString().slice(0, 10)}';
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, out);
console.log(`build-changelog: ${commits.length} commits, ${daily.length} days, ${quoted.length} quoted -> ${OUT}`);
